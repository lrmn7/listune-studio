type Widen<T> = { -readonly [K in keyof T]: T[K] extends string ? string : Widen<T[K]> };
/** Languages without a singular form (Indonesian) leave `_one` keys out. */
type Optional<T> = {
  [K in keyof T as K extends `${string}_one` ? never : K]: T[K] extends string ? string : Optional<T[K]>;
} & {
  [K in keyof T as K extends `${string}_one` ? K : never]?: string;
};
/** The shape every other language must match: same keys, string values, `_one` plurals optional. */
export type Translations = Optional<Widen<typeof en>>;
